"""ServiceLevel spec -> Prometheus rule groups (budgetguard-slo-rules §2).

Deterministic output so `bg generate --check` can diff. Every window an alert references gets a
recording rule (kills Rev 1's B-4: an alert reading a rule nobody generated never fires).
"""
from __future__ import annotations

import difflib
import sys
from pathlib import Path
from typing import Any

import yaml

from .spec import ServiceLevel, Slo, load_dir

HEADER = "# Generated by `bg generate` from slo/{service}.yaml. Do not edit: CI fails on any hand edit.\n"
_UNIT = {"s": 1, "m": 60, "h": 3600, "d": 86400}


class _RuleDumper(yaml.SafeDumper):
    """Multi-line PromQL as `|` blocks, and no &id001 anchors for shared label dicts."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_RuleDumper.add_representer(str, _str)


def dump(doc: dict[str, Any]) -> str:
    return yaml.dump(doc, Dumper=_RuleDumper, sort_keys=False, width=200)


def seconds(window: str) -> int:
    return int(window[:-1]) * _UNIT[window[-1]]


def windows(slo: Slo) -> list[str]:
    ws = {"5m", "30m", "1h", "6h", "3d"}                     # gate + dashboards always need these
    for tier in slo.alerting.page + slo.alerting.ticket:
        ws |= {tier.long, tier.short}
    return sorted(ws, key=seconds)


def _ratio(num: str, den: str, w: str, fn: str = "rate") -> str:
    return f"sum by (service) ({fn}({num}[{w}]))\n/\nsum by (service) ({fn}({den}[{w}]))"


def _bad_ratio(bad: str, total: str, w: str, fn: str = "rate") -> str:
    """Error ratio that is 0, not empty, when there is traffic but no error series at all.

    A healthy service has no 5xx series, so a plain sum(rate(bad)) is an empty vector and the ratio
    would be missing: "zero errors" would look like "no data" (UNKNOWN) to the gate and dashboards.
    `or 0 * total` fills the gap only while total exists; with no traffic the ratio stays empty (D-4).
    """
    num = f"sum by (service) ({fn}({bad}[{w}]))"
    den = f"sum by (service) ({fn}({total}[{w}]))"
    return f"(\n{num}\nor\n0 * {den}\n)\n/\n{den}"


def _error_ratio(slo: Slo, w: str, fn: str = "rate") -> str:
    if slo.sli.type == "ratio":
        assert slo.sli.bad is not None
        return _bad_ratio(slo.sli.bad, slo.sli.total, w, fn)
    assert slo.sli.good is not None
    # Same zero-fill on the good side: if every notification failed, the outcome="delivered" bucket
    # never exists, and the SLI must read 100% bad, not "no data".
    return f"1 - (\n{_bad_ratio(slo.sli.good, slo.sli.total, w, fn)}\n)"


def recording_groups(sl: ServiceLevel) -> list[dict[str, Any]]:
    svc = sl.metadata.service
    groups: list[dict[str, Any]] = []
    for slo in sl.spec.slos:
        labels = {"slo": slo.name}
        rules: list[dict[str, Any]] = [
            {"record": "bg:slo_allowed_ratio", "labels": {**labels, "service": svc},
             "expr": f"vector({1 - slo.objective:.10g})"}]
        for w in windows(slo):
            rules.append({"record": f"bg:error_ratio:rate{w}", "labels": labels,
                          "expr": _error_ratio(slo, w)})
            if slo.sli.self_bad:
                rules.append({"record": f"bg:self_error_ratio:rate{w}", "labels": labels,
                              "expr": _bad_ratio(slo.sli.self_bad, slo.sli.total, w)})
        rules.append({"record": "bg:requests:rate1h", "labels": labels,
                      "expr": f"sum by (service) (rate({slo.sli.total}[1h]))"})
        groups.append({"name": f"bg:{svc}:{slo.name}:ratios", "interval": "30s", "rules": rules})
        groups.append({"name": f"bg:{svc}:{slo.name}:window", "interval": "5m",
                       "rules": [{"record": f"bg:error_ratio:increase{sl.spec.window}", "labels": labels,
                                  "expr": _error_ratio(slo, sl.spec.window, "increase")}]})
    return groups


def alert_groups(sl: ServiceLevel) -> list[dict[str, Any]]:
    svc = sl.metadata.service
    rules: list[dict[str, Any]] = []
    for slo in sl.spec.slos:
        a = 1 - slo.objective
        sel = f'{{service="{svc}",slo="{slo.name}"}}'
        floor = f"and on (service, slo) (bg:requests:rate1h{sel} * 3600 >= {sl.spec.min_events_per_hour})"
        for severity, tiers in (("page", slo.alerting.page), ("ticket", slo.alerting.ticket)):
            if not tiers:
                continue
            clauses = [f"(bg:error_ratio:rate{t.long}{sel} > ({t.burn:g} * {a:.10g})\n"
                       f" and bg:error_ratio:rate{t.short}{sel} > ({t.burn:g} * {a:.10g}))" for t in tiers]
            pace = "fast" if severity == "page" else "steadily"
            rules.append({
                "alert": f"ErrorBudgetBurn{severity.capitalize()}",
                "expr": "(\n" + "\n or\n".join(clauses) + "\n)\n" + floor,
                "labels": {"severity": severity, "service": svc, "slo": slo.name,
                           "incident_type": f"{slo.name}_{'burn' if severity == 'page' else 'slow_burn'}"},
                "annotations": {
                    "summary": f"{svc} {slo.name} is spending error budget {pace}",
                    "budgetguard_url": f"https://budgetguard.example.dev/services/{svc}"},
            })
    integrity = [f'up{{job="{sl.spec.job}"}} == 0',
                 f'absent(http_server_requests_seconds_count{{service="{svc}"}})']
    if sl.spec.probe:
        # Matched by the `service` label Prometheus attaches to the blackbox target, not by URL: the same
        # committed rules run in compose and k3s, where the probe URLs differ.
        integrity.append(f'probe_success{{job="blackbox",service="{svc}"}} == 0')
    rules.append({"alert": "SLIIntegrityLost", "expr": "\nor ".join(integrity), "for": "2m",
                  "labels": {"severity": "page", "service": svc, "incident_type": "sli_integrity"},
                  "annotations": {"summary": f"{svc}: SLI signal lost; gate reports UNKNOWN"}})
    return [{"name": f"bg:{svc}:alerts", "rules": rules}]


def render(sl: ServiceLevel, fmt: str = "prometheus") -> str:
    groups = recording_groups(sl) + alert_groups(sl)
    svc = sl.metadata.service
    if fmt == "prometheus-operator":
        doc: dict[str, Any] = {
            "apiVersion": "monitoring.coreos.com/v1", "kind": "PrometheusRule",
            "metadata": {"name": f"bg-{svc}", "namespace": "monitoring",
                         "labels": {"release": "kube-prometheus-stack",
                                    "app.kubernetes.io/part-of": "budgetguard"}},
            "spec": {"groups": groups}}
    else:
        doc = {"groups": groups}
    return HEADER.format(service=svc) + dump(doc)


def write_all(slo_dir: Path, out: Path, fmt: str = "prometheus", check: bool = False) -> int:
    """Write <service>.rules.yaml per spec, or with check=True report drift and return 1."""
    expected = {f"{sl.metadata.service}.rules.yaml": render(sl, fmt) for sl in load_dir(slo_dir)}
    return sync_files(out, expected, check, "*.rules.yaml", "bg generate")


def sync_files(out: Path, expected: dict[str, str], check: bool, pattern: str, cmd: str) -> int:
    present = {p.name for p in out.glob(pattern)} if out.exists() else set()
    if not check:
        out.mkdir(parents=True, exist_ok=True)
        for name, text in expected.items():
            (out / name).write_text(text, encoding="utf-8", newline="\n")
        for stale in present - expected.keys():
            (out / stale).unlink()
        return 0
    drift = 0
    for name in sorted(present - expected.keys()):
        print(f"{out / name}: not generated by any spec (delete it or add a spec)", file=sys.stderr)
        drift = 1
    for name, text in sorted(expected.items()):
        path = out / name
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            drift = 1
            sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                       f"committed/{name}", f"generated/{name}"))
    if drift:
        print(f"\n{out} is out of date or hand-edited: run `{cmd}` and commit the result", file=sys.stderr)
    return drift
