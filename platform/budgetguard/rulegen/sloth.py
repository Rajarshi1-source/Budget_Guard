"""Export a ServiceLevel spec as a Sloth `prometheus/v1` spec for the parity check (D-8, W8).

Sloth then generates its own rules from the same queries; a promtool test asserts both generators
produce the same ratios (budgetguard-slo-rules §4). Sloth's alerts are disabled: BudgetGuard's own
alerts are the ones that page.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from .generate import dump, sync_files
from .spec import ServiceLevel, Slo, load, load_dir
from .testgen import _num, _series, concrete


def _queries(slo: Slo) -> dict[str, str]:
    total = f"sum(rate({slo.sli.total}[{{{{.window}}}}]))"
    if slo.sli.type == "ratio":
        return {"error_query": f"sum(rate({slo.sli.bad}[{{{{.window}}}}]))", "total_query": total}
    good = f"sum(rate({slo.sli.good}[{{{{.window}}}}]))"
    return {"error_query": f"({total} - {good})", "total_query": total}


def export_sloth(spec_path: Path) -> str:
    sl = load(spec_path)
    head = f"# Generated by `bg export sloth` from slo/{sl.metadata.service}.yaml. Do not edit.\n"
    doc: dict[str, Any] = {
        "version": "prometheus/v1",
        "service": sl.metadata.service,
        "labels": {"owner": sl.metadata.owner},
        "slos": [{
            "name": slo.name,
            "objective": round(slo.objective * 100, 6),
            "sli": {"events": _queries(slo)},
            "alerting": {"name": f"Sloth{slo.name.capitalize()}",
                         "page_alert": {"disable": True}, "ticket_alert": {"disable": True}},
        } for slo in sl.spec.slos],
    }
    return head + dump(doc)


# --- Parity test: same input series through both generators' rules ---------------------------------
PARITY_WINDOWS = ("5m", "30m", "1h", "6h")
_CALM, _HOT = (360, 0.004), (60, 0.04)          # 6 h at 0.4% errors, then 1 h at 4%: every window differs
_EVAL = "400m"                                  # 40 min into the hot hour


def _counter(segments: list[tuple[int, float]]) -> str:
    """promtool expanding notation for a counter rising `per_min` for `minutes`, segment by segment."""
    parts, value = [], 0.0
    for i, (minutes, per_min) in enumerate(segments):
        start = value if i == 0 else value + per_min
        n = minutes if i == 0 else minutes - 1
        parts.append(f"{_num(start)}+{_num(per_min)}x{n}")
        value = start + per_min * n
    return " ".join(parts)


def _parity_inputs(slo: Slo) -> list[dict[str, str]]:
    per_min = 1000.0
    bad = [(m, per_min * r) for m, r in (_CALM, _HOT)]
    good = [(m, per_min - b) for m, b in bad]
    total = [(m, per_min) for m, _ in bad]
    if slo.sli.type == "ratio":
        assert slo.sli.bad is not None
        name, base = concrete(slo.sli.total)
        bad_name, bad_labels = concrete(slo.sli.self_bad or slo.sli.bad)
        ok = _series(name, {**base, "status": "200", "error_origin": "none"})
        return [{"series": ok, "values": _counter(good)},
                {"series": _series(bad_name, bad_labels), "values": _counter(bad)}]
    assert slo.sli.good is not None
    total_name, total_labels = concrete(slo.sli.total)
    good_name, good_labels = concrete(slo.sli.good)
    return [{"series": _series(total_name, total_labels), "values": _counter(total)},
            {"series": _series(good_name, good_labels), "values": _counter(good)}]


def parity_test(sl: ServiceLevel) -> str:
    svc = sl.metadata.service
    tests = [{
        "name": f"{svc} {slo.name}: BudgetGuard and Sloth agree at {', '.join(PARITY_WINDOWS)}",
        "interval": "1m",
        "input_series": _parity_inputs(slo),
        "promql_expr_test": [{
            # sum() drops the differing label sets; an absent series on either side leaves no sample
            "expr": (f'round(abs(sum(bg:error_ratio:rate{w}{{service="{svc}",slo="{slo.name}"}})'
                     f' - sum(slo:sli_error:ratio_rate{w}{{sloth_service="{svc}",sloth_slo="{slo.name}"}})),'
                     " 0.000000001)"),
            "eval_time": _EVAL,
            "exp_samples": [{"labels": "{}", "value": 0}],
        } for w in PARITY_WINDOWS],
    } for slo in sl.spec.slos]
    doc = {"rule_files": [f"../generated/{svc}.rules.yaml", f"{svc}.sloth.rules.yaml"],
           "evaluation_interval": "30s", "tests": tests}
    return f"# Generated by `bg parity` from slo/{svc}.yaml. Do not edit.\n" + dump(doc)


def write_parity(slo_dir: Path, out: Path, check: bool = False) -> int:
    """<service>.sloth.yaml (Sloth's input) and <service>.parity.test.yaml. Sloth itself writes
    <service>.sloth.rules.yaml from the first; ci.yml regenerates those and fails on a diff."""
    specs = load_dir(slo_dir)
    expected = {f"{sl.metadata.service}.sloth.yaml": export_sloth(slo_dir / f"{sl.metadata.service}.yaml")
                for sl in specs}
    rc = sync_files(out, expected, check, "*.sloth.yaml", "bg parity")
    tests = {f"{sl.metadata.service}.parity.test.yaml": parity_test(sl) for sl in specs}
    return rc | sync_files(out, tests, check, "*.parity.test.yaml", "bg parity")
