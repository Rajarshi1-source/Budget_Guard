#!/usr/bin/env bash
# `make secrets`: create deploy/compose/secrets/ (git-ignored) for a local stack. Never overwrites a
# file that exists, so rotating a value means editing it there (security-and-api.md §7).
#   local.env  random passwords and tokens for every role and machine caller
#   bg_token   the bearer Alertmanager sends; same value as BG_ALERTMANAGER_TOKEN in local.env
#   slack_*    placeholders pointing at 127.0.0.1:9, so nothing leaves the machine
# GitHub App values stay placeholders here; put real ones in the repo-root .env (it overrides).
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p secrets
chmod 700 secrets
rnd() { head -c 32 /dev/urandom | base64 | tr -d '/+=' | head -c 40; }

for f in slack_page_url slack_ticket_url; do
  [ -f "secrets/$f" ] || cp "secrets.example/$f" "secrets/$f"
done

if [ ! -f secrets/local.env ]; then
  am=$(rnd)
  umask 077
  cat > secrets/local.env <<EOF
# Generated by gen-secrets.sh on $(date -u +%FT%TZ). Local stack only; git-ignored.
PG_PASSWORD=$(rnd)
BG_DB_APP_PASSWORD=$(rnd)
BG_DB_GRAFANA_PASSWORD=$(rnd)
BG_DB_AUTH_PASSWORD=$(rnd)
VALKEY_PASSWORD=$(rnd)
BG_ALERTMANAGER_TOKEN=$am
BG_DASHBOARD_TOKEN=$(rnd)
BG_GITHUB_WEBHOOK_SECRET=$(rnd)
BETTER_AUTH_SECRET=$(rnd)
GRAFANA_ADMIN_PASSWORD=$(rnd)
EOF
  printf '%s' "$am" > secrets/bg_token
  echo "wrote deploy/compose/secrets/local.env and bg_token"
elif [ ! -f secrets/bg_token ]; then
  sed -n 's/^BG_ALERTMANAGER_TOKEN=//p' secrets/local.env | tr -d '\n' > secrets/bg_token
fi
